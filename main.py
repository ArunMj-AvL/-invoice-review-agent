"""Command line entry point for the invoice review workflow.

Examples (from the repository root, with the virtual environment active):

    python main.py --invoice INV-004 --comment "Please check the price mismatch"
    python main.py --batch
    python main.py --approve INV-004 --actor alice --comment "price confirmed"
    python main.py --reject  INV-004 --actor alice
    python main.py --demo interrupt      # pause -> replay -> resume -> replay (1 audit entry)
    python main.py --demo failure        # simulated CrewAI timeout: retries, then escalation
    python main.py --examples            # writes examples/*.json and docs/execution_trace.md

Nothing here makes a payment. "Approval" only writes a line to the local audit log.
"""

import argparse
import json
import logging
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

try:  # optional: load OPENAI_API_KEY etc. from .env
    from dotenv import load_dotenv

    load_dotenv()
except ImportError:
    pass

from app.approval import AuditLog
from app.graph import create_app, make_checkpointer, resume_case, run_case

ROOT = Path(__file__).resolve().parent


def configure_logging(verbose: bool) -> None:
    logging.basicConfig(
        level=logging.INFO if verbose else logging.WARNING,
        format="%(asctime)s %(levelname)s %(name)s %(message)s",
    )


def show(title: str, payload: Dict[str, Any]) -> None:
    print(f"\n=== {title} ===")
    print(json.dumps(payload, indent=2, default=str))


def slim(result: Dict[str, Any]) -> Dict[str, Any]:
    """Drop the long trace for console output."""
    return {k: v for k, v in result.items() if k != "trace"}


def all_invoice_ids() -> List[str]:
    from app.rules_loader import get_rules

    return sorted(get_rules().load_data()["invoices"])


# ---------------------------------------------------------------------------
# Demos
# ---------------------------------------------------------------------------
def demo_interrupt(audit_path: str, checkpoint_db: str) -> None:
    audit = AuditLog(audit_path)
    _, graph = create_app(make_checkpointer(checkpoint_db), audit_log=audit)
    print(f"audit log: {audit_path}\ncheckpoints: {checkpoint_db}")
    show("1. First request: INV-001 (INR 475,000 -> needs Finance approval)", slim(run_case(graph, "INV-001")))
    print(f"\n   audit entries so far: {len(audit.read_all())}  (nothing executes before approval)")
    show("2. Webhook replay while paused: same thread, no second run", slim(run_case(graph, "INV-001")))
    show("3. Human approves: SAME thread resumes", slim(resume_case(graph, "INV-001", "approve", "finance.lead", "ok")))
    show("4. Webhook replayed AFTER completion", slim(run_case(graph, "INV-001")))
    show("5. Duplicate approval click", slim(resume_case(graph, "INV-001", "approve", "finance.lead")))
    print(f"\n   audit entries at the end: {len(audit.read_all())}  <- exactly one")
    print(json.dumps(audit.read_all(), indent=2))


def demo_failure(audit_path: str, checkpoint_db: str) -> None:
    audit = AuditLog(audit_path)
    os.environ["FORCE_ADAPTER_FAILURE"] = "timeout"
    os.environ["USE_MOCK_LLM"] = "1"
    try:
        _, graph = create_app(make_checkpointer(checkpoint_db), audit_log=audit, backoff_seconds=0.2)
        result = run_case(graph, "INV-004", "failure demo")
    finally:
        os.environ.pop("FORCE_ADAPTER_FAILURE", None)
    show("Forced CrewAI timeout on INV-004 (3 bounded attempts, then escalation)", slim(result))
    print("\nTrace:")
    print("\n".join(result["trace"]))
    print("\nThe deterministic decision is unchanged and a human is still required to approve.")


def export_examples(out_dir: Path, trace_path: Path) -> None:
    """Five example outputs plus an execution trace for the submission."""
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="invoice_demo_"))
    audit = AuditLog(tmp / "audit_log.jsonl")
    os.environ.setdefault("USE_MOCK_LLM", "1")
    _, graph = create_app(make_checkpointer(str(tmp / "checkpoints.sqlite")), audit_log=audit)
    plan = [
        ("INV-010", None, "Clean small invoice: AUTO_CLEAR"),
        ("INV-002", "approve", "Quantity exceeds received: HOLD, human approves"),
        ("INV-004", "reject", "Price mismatch: HOLD, human rejects"),
        ("INV-013", "reject", "Possible duplicate of INV-001: reviewed, not paid"),
        ("INV-014", None, "Missing PO: NEEDS_INFORMATION"),
    ]
    trace_lines = ["# Execution traces", "", "Generated by `python main.py --examples` with `USE_MOCK_LLM=1`.", ""]
    for number, (invoice_id, action, title) in enumerate(plan, start=1):
        result = run_case(graph, invoice_id, f"example {number}")
        if action:
            result = resume_case(graph, invoice_id, action, "demo.reviewer", f"example {action}")
        (out_dir / f"example_{number:02d}_{invoice_id}.json").write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
        trace_lines += [f"## {number}. {invoice_id}: {title}", "", "```"] + result["trace"] + ["```", ""]
        print(f"wrote example_{number:02d}_{invoice_id}.json  ->  {result['final_status']}")
    (out_dir / "audit_log_sample.jsonl").write_text((tmp / "audit_log.jsonl").read_text(encoding="utf-8"), encoding="utf-8")
    trace_path.write_text("\n".join(trace_lines), encoding="utf-8")
    print(f"wrote {trace_path}")


