def main(argv: List[str] = None) -> int:
    parser = argparse.ArgumentParser(description="Invoice review workflow (LangGraph)")
    parser.add_argument("--invoice", help="run one invoice, e.g. INV-004")
    parser.add_argument("--comment", default="", help="optional requester comment")
    parser.add_argument("--batch", action="store_true", help="run every invoice in the dataset")
    parser.add_argument("--approve", metavar="INVOICE_ID", help="resume a paused case with approve")
    parser.add_argument("--reject", metavar="INVOICE_ID", help="resume a paused case with reject")
    parser.add_argument("--actor", default="", help="who is approving / rejecting")
    parser.add_argument("--demo", choices=["interrupt", "failure"], help="scripted demonstrations")
    parser.add_argument("--examples", action="store_true", help="write examples/ and docs/execution_trace.md")
    parser.add_argument("--audit-log", default=None, help="audit log path (default audit_log.jsonl)")
    parser.add_argument("--checkpoint-db", default=None, help="checkpoint database (default checkpoints.sqlite)")
    parser.add_argument("-v", "--verbose", action="store_true", help="show log lines with correlation IDs")
    args = parser.parse_args(argv)
    configure_logging(args.verbose)

    if args.demo or args.examples:
        tmp = tempfile.mkdtemp(prefix="invoice_demo_")
        audit_path = args.audit_log or os.path.join(tmp, "audit_log.jsonl")
        db_path = args.checkpoint_db or os.path.join(tmp, "checkpoints.sqlite")
        if args.examples:
            export_examples(ROOT / "examples", ROOT / "docs" / "execution_trace.md")
        elif args.demo == "interrupt":
            demo_interrupt(audit_path, db_path)
        else:
            demo_failure(audit_path, db_path)
        return 0

    audit = AuditLog(args.audit_log) if args.audit_log else AuditLog()
    _, graph = create_app(make_checkpointer(args.checkpoint_db), audit_log=audit)

    if args.approve or args.reject:
        invoice_id = args.approve or args.reject
        if not args.actor:
            print("--actor is required for --approve / --reject", file=sys.stderr)
            return 2
        action = "approve" if args.approve else "reject"
        show(f"{action.upper()} {invoice_id}", slim(resume_case(graph, invoice_id, action, args.actor, args.comment)))
        return 0
    if args.batch:
        for invoice_id in all_invoice_ids():
            r = run_case(graph, invoice_id)
            print(f"{invoice_id}  {str(r['decision']):<19} {str(r['final_status']):<24} approval_required={r['approval_required']}")
        print("\nCases marked PENDING_APPROVAL are paused. Resume them with --approve / --reject.")
        return 0
    if args.invoice:
        show(args.invoice, slim(run_case(graph, args.invoice, args.comment)))
        return 0
    parser.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
